import Stripe from "stripe";
import { env } from "../config/env.config.js";
import { logFlow, logError } from "../debug/debug.logs.js";
import { NotFoundError } from "../errors/errors.custom.js";

//creating a instance from the class #tip: it's a object
const stripe = new Stripe(env.stripe);

//function to get the url for the payment
export const checkoutStripe = async (
  stripecusid,
  userid,
  userplan,
  calculatedAmount,
) => {
  logFlow("Running checkoutStripe files...")

  //creating a stripe session by talking to the server
  logFlow("Talking a server to create stripe checkout session...")
  const session = await stripe.checkout.sessions.create({
    mode: "payment",
    customer: stripecusid,
    line_items: [
      {
        price_data: {
          currency: "usd",

          product_data: {
            name: `Think Tweet ${userplan}`,
          },
          unit_amount: calculatedAmount,
        },
        quantity: 1,
      },
    ],
    metadata: {
      userId: userid.toString(),
      plan: userplan,
    },
    success_url: "https://meetnoman.com/",
    cancel_url: "https://velin.meetnoman.com/",
  });
  logFlow("Session is created. Url is generated by stripe server")

  //checking whether url is present or not
  if (!session.url) {
    logError("Session url not found")
    throw new NotFoundError("Payment URL not found.")
  }

  //returing the function
  logFlow("Returning the func.")
  return session.url;
};
